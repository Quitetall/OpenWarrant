//! The file ledger (OW-WAR-0148 M17, decision 24; docs/LEDGER.md): why each
//! file changed, kept beside the code.
//!
//! # Two forms, one source
//!
//! - **Atoms**, committed: one small Markdown file per source file, at
//!   `docs/ledger/<path>.md` (`[ledger] dir`). Each line is one change: its
//!   date, commit, Warrant and why. Past the last `keep` entries (default 3)
//!   or a token budget, older entries fold into one `earlier` line. Git keeps
//!   the full history; the atom keeps the curated reason.
//! - **`.openwarrant/ledger.jsonl`**, regenerated by `war admin compile` and
//!   never committed: one JSON line per file, so an agent reads every file's
//!   why in one go. The directory ignores the file itself, and `war check`
//!   refuses a commit that tracks it (`ledger.committed`).
//!
//! # Three writer modes
//!
//! `war admin ledger record` writes an entry for each file a commit touched.
//! Its why comes from, by `[ledger] mode`:
//!
//! - `commit` (the default): the commit's `Ledger:` trailer (`Ledger: <path>:
//!   <why>` for one file), else its body's first paragraph; falling back to
//!   `deterministic` when the message has neither;
//! - `deterministic`: the cited Warrant's title (`Warrant:` trailer), else the
//!   commit subject;
//! - `agent`: the text the agent gives (`--why`), asked for at `war done`.
//!
//! Agent Trace records and git-ai notes read in and write out through
//! [`interop`].

