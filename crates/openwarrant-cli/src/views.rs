//! The views of the masters (FORMAT-1.0 §4.3, §4.6, revision 4): what
//! `war compile` writes under `docs/` from `docs/work/`, and the main-only
//! Views workflow commits (`conformance/views.toml`). Nothing here is read
//! as a source.
//!
//! - one page per document master, `docs/pages/<id>.md`: its tier, its type,
//!   where its master is, and its text after the frontmatter;
//! - `docs/ROADMAP.md`: every open work order, under the Roadmap phase it is
//!   `part_of` (`roadmap/<phase>`), else under "Unphased", phases in the
//!   Roadmap's order;
//! - `docs/HISTORY.md`: every closed work order.
//!
//! A human number is read from `docs/generated/numbers.tsv` (`id`, `number`,
//! `first_seen`; the Views workflow appends it) and shown as `#N`; an id it
//! does not number is shown as itself. A view is a pure function of the
//! tree: it reads no clock and no claim, so an item is open or closed, never
//! "in progress", here.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use camino::Utf8PathBuf;

use crate::corpus::Corpus;
use crate::format_doc::{self, Loaded};
use openwarrant_core::format;

/// Where the pages go, under the repository root.
pub const PAGES: &str = "docs/pages";
/// The open work, by phase.
pub const ROADMAP: &str = "docs/ROADMAP.md";
/// The closed work.
pub const HISTORY: &str = "docs/HISTORY.md";
/// The append-only index of display ordinals.
pub const NUMBERS: &str = "docs/generated/numbers.tsv";

const GENERATED: &str = "<!-- generated by `war admin compile` from the masters in docs/work/; edit \
                         those, never this file (FORMAT-1.0 §4.3) -->";

/// `id` → its number, from the index's text. A row that does not read is
/// skipped: the id then shows as itself, which is what an unnumbered id is.
#[must_use]
pub fn numbers(text: &str) -> BTreeMap<String, u64> {
    text.lines()
        .skip(1)
        .filter_map(|line| {
            let mut parts = line.split('\t');
            let id = parts.next()?;
            let n = parts.next()?.parse().ok()?;
            Some((id.to_owned(), n))
        })
        .collect()
}

/// How a view names `id`: `#N` with its id beside it, or the id alone.
fn shown(numbers: &BTreeMap<String, u64>, id: &str) -> String {
    numbers
        .get(id)
        .map_or_else(|| format!("`{id}`"), |n| format!("#{n} `{id}`"))
}

/// The masters of `corpus`, read and admitted.
fn masters(corpus: &Corpus) -> Vec<&Loaded> {
    corpus
        .format_docs()
        .docs
        .iter()
        .filter(|d| d.source.starts_with("docs/work/") && d.admitted())
        .collect()
}

/// The text of a document after its frontmatter and its `# ` title line.
fn body_of(d: &Loaded) -> String {
    let text = String::from_utf8_lossy(&d.bytes);
    let mut fences = 0;
    let mut out = String::new();
    let mut titled = false;
    for line in text.split_inclusive('\n') {
        if fences < 2 {
            if line.trim_end() == "---" {
                fences += 1;
            }
            continue;
        }
        if !titled && line.starts_with("# ") {
            titled = true;
            continue;
        }
        out.push_str(line);
    }
    out.trim_start_matches('\n').to_owned()
}

/// Every view of the masters of `corpus`, as `(path, contents)`, sorted.
/// Nothing when the repository has no `docs/work/`, so a repository that
/// does not use masters compiles exactly as before.
#[must_use]
pub fn compiled(corpus: &Corpus) -> Vec<(Utf8PathBuf, String)> {
    let repo = corpus.repo();
    let masters = masters(corpus);
    if masters.is_empty() {
        return Vec::new();
    }
    let numbers = crate::vfs::read(repo.root.join(NUMBERS))
        .map(|b| numbers(&String::from_utf8_lossy(&b)))
        .unwrap_or_default();
    let profiles = &corpus.format_docs().profiles;
    let mut out = Vec::new();

    // One page per document.
    for d in masters
        .iter()
        .filter(|d| format::kind_of(d.doc.alias.as_deref()) == "document")
    {
        let Some(id) = d.doc.alias.as_deref() else {
            continue;
        };
        let tier = format_doc::tier(d, profiles);
        let ty = d
            .doc
            .fields
            .get("type")
            .and_then(|v| v.as_str())
            .unwrap_or("-");
        let mut page = String::new();
        let _ = writeln!(page, "{GENERATED}");
        let _ = writeln!(
            page,
            "# {} {}\n",
            shown(&numbers, id),
            d.doc.title.as_deref().unwrap_or(id)
        );
        let _ = writeln!(
            page,
            "{} · type {ty} · master [{}](../{})\n",
            tier.map_or_else(
                || "tier UNKNOWN".to_owned(),
                |t| format!("{} (tier {t})", format_doc::tier_name("document", t))
            ),
            d.source,
            d.source.strip_prefix("docs/").unwrap_or(&d.source)
        );
        page.push_str(&body_of(d));
        if !page.ends_with('\n') {
            page.push('\n');
        }
        out.push((repo.root.join(PAGES).join(format!("{id}.md")), page));
    }

    // The Roadmap's phases, in its order, and each work order's phase.
    let mut phases: Vec<(String, String)> = Vec::new();
    if let Some(roadmap) = masters
        .iter()
        .find(|d| d.doc.alias.as_deref() == Some("roadmap"))
    {
        for u in roadmap
            .doc
            .units
            .iter()
            .filter(|u| u.record_type == "phase")
        {
            phases.push((format!("roadmap/{}", u.id), u.title.clone()));
        }
    }
    let phase_of: BTreeMap<&str, String> = masters
        .iter()
        .filter_map(|d| {
            let id = d.doc.alias.as_deref()?;
            let phase =
                d.doc.relations.iter().find(|r| {
                    r.kind == "part_of" && phases.iter().any(|(p, _)| *p == r.target.id)
                })?;
            Some((id, phase.target.id.clone()))
        })
        .collect();
    let tier_of: BTreeMap<&str, Option<u8>> = masters
        .iter()
        .filter_map(|d| Some((d.doc.alias.as_deref()?, format_doc::tier(d, profiles))))
        .collect();

    // Every work order, wherever it is kept: what `war` lists, except that
    // a work master of profile `ticket`, which the ticket store does not
    // read yet, is open until every item of it is ticked. A document is no
    // work order, and the Roadmap is not one of its own items.
    let ticket_master = |id: &str| {
        masters
            .iter()
            .any(|d| d.doc.alias.as_deref() == Some(id) && d.doc.profile == "ticket")
    };
    let work = crate::work::Work::read(repo);
    let mut items: Vec<crate::work::Item> = work
        .items()
        .iter()
        .filter(|i| {
            i.id != "roadmap"
                && format::kind_of(Some(&i.id)) == "work"
                // A master of profile `ticket` the store listed is read as the
                // store reads it: one with no items is done by its journal.
                && (!ticket_master(&i.id) || i.level != crate::work::Level::Unknown)
        })
        .cloned()
        .collect();
    for d in &masters {
        let Some(id) = d.doc.alias.as_deref() else {
            continue;
        };
        if id == "roadmap"
            || format::kind_of(Some(id)) != "work"
            || items.iter().any(|i| i.id == id)
        {
            continue;
        }
        let ticks: Vec<bool> = d
            .doc
            .units
            .iter()
            .flat_map(|u| u.items.iter().map(|i| i.done))
            .collect();
        let done = !ticks.is_empty() && ticks.iter().all(|t| *t);
        items.push(crate::work::Item {
            id: id.to_owned(),
            title: d.doc.title.clone().unwrap_or_default(),
            state: if done { "done" } else { "open" }.to_owned(),
            level: crate::work::Level::Unknown,
            encoding: crate::work::Encoding::SingleFile,
            place: d.source.clone(),
        });
    }
    items.sort_by(|a, b| a.id.cmp(&b.id));
    let mut open: BTreeMap<Option<String>, Vec<String>> = BTreeMap::new();
    let mut closed = Vec::new();
    for item in &items {
        let level = tier_of.get(item.id.as_str()).map_or_else(
            || item.level.as_str().to_owned(),
            |t| {
                t.map_or("UNKNOWN".to_owned(), |t| {
                    format_doc::tier_name("work", t).to_owned()
                })
            },
        );
        let line = format!(
            "- {} {} · {level} · {} · {}\n",
            shown(&numbers, &item.id),
            item.title,
            item.state,
            item.place
        );
        if item.is_done() {
            closed.push(line);
        } else {
            open.entry(phase_of.get(item.id.as_str()).cloned())
                .or_default()
                .push(line);
        }
    }
    let mut roadmap = format!("{GENERATED}\n# Roadmap\n\nOpen work orders, by phase.\n");
    for (phase, title) in &phases {
        let _ = write!(roadmap, "\n## {title} (`{phase}`)\n\n");
        match open.get(&Some(phase.clone())) {
            Some(lines) => lines.iter().for_each(|l| roadmap.push_str(l)),
            None => roadmap.push_str("Nothing open.\n"),
        }
    }
    let unphased = open.get(&None).map_or(&[][..], Vec::as_slice);
    if !unphased.is_empty() || phases.is_empty() {
        roadmap.push_str("\n## Unphased\n\n");
        if unphased.is_empty() {
            roadmap.push_str("Nothing open.\n");
        }
        unphased.iter().for_each(|l| roadmap.push_str(l));
    }
    for why in [
        work.unread(crate::work::Source::Tickets),
        work.unread(crate::work::Source::Others),
    ]
    .into_iter()
    .flatten()
    {
        let _ = write!(roadmap, "\nUNKNOWN: some work could not be read ({why}).\n");
    }
    out.push((repo.root.join(ROADMAP), roadmap));
    let mut history = format!("{GENERATED}\n# History\n\nClosed work orders.\n\n");
    if closed.is_empty() {
        history.push_str("Nothing closed yet.\n");
    }
    closed.iter().for_each(|l| history.push_str(l));
    out.push((repo.root.join(HISTORY), history));
    out.sort_by(|a, b| a.0.cmp(&b.0));
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn numbers_read_the_index_and_skip_what_does_not_read() {
        let n = numbers("id\tnumber\tfirst_seen\nw-3c16a\t1\tabc\nbad line\nspec\t2\tdef\n");
        assert_eq!(n.get("w-3c16a"), Some(&1));
        assert_eq!(n.get("spec"), Some(&2));
        assert_eq!(n.len(), 2);
        assert_eq!(shown(&n, "spec"), "#2 `spec`");
        assert_eq!(shown(&n, "d-5e21b"), "`d-5e21b`");
    }
}
